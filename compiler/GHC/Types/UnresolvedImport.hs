-- | Unresolved imports: a module name, together with everything needed to
-- resolve that name to a module ('GHC.Unit.Finder.resolveImport').
--
-- Handles all kinds of imports: user-written, generated imports, SOURCE imports,
-- plugin module imports, etc.
module GHC.Types.UnresolvedImport
  ( -- * Origins of import declarations
    ImportDeclOrigin (..)
  , importDeclLookupScope
  , isGeneratedImport

    -- * Unresolved imports
  , UnresolvedImportOrigin (..)
  , unresolvedImportLookupScope
  , UnresolvedImport (..)
  , generatedImport
  , rnUnresolvedImportPkgQual
  )
where

import GHC.Prelude

import GHC.Types.Basic ( ImportLevel(..) )
import GHC.Types.PkgQual
import GHC.Types.SrcLoc ( Located, unLoc )
import GHC.Unit.Types ( ModuleLookupScope(..) )

import GHC.Utils.Outputable

import Language.Haskell.Syntax.ImpExp.IsBoot ( IsBootInterface(..) )
import Language.Haskell.Syntax.Module.Name ( ModuleName )

import Data.Data ( Data )

-- | Where an import declaration came from.
--
-- See Note [Generated imports] in GHC.Hs.ImpExp.
data ImportDeclOrigin
  = UserWrittenImport
    -- ^ The import declaration appears in the source file.
  | ImplicitPreludeImport
    -- ^ The implicit @import Prelude@.
    --
    -- Behaves in every way like a user-written import, except that it is not
    -- reported as unused and does not want an explicit import list.
  | ImplicitEssentialsImport
    -- ^ The implicit import of @GHC.Essentials@, through whose export list GHC
    -- resolves known entities.
    --
    -- Unlike every other import, it brings nothing into scope, and it may
    -- resolve a module that users are not allowed to import.
    -- See Note [Finding GHC.Essentials] in GHC.Builtin.
  | PluginImport
    -- ^ An import declaration generated by a plugin.
    --
    -- Behaves the same as a user-written import, with the sole exception that
    -- it is never reported as unused.
  deriving (Eq, Data)

instance Outputable ImportDeclOrigin where
  ppr = \case
    UserWrittenImport        -> text "user-written import"
    ImplicitPreludeImport    -> text "implicit Prelude import"
    ImplicitEssentialsImport -> text "implicit GHC.Essentials import"
    PluginImport             -> text "plugin import"

-- | The 'ModuleLookupScope' to use when looking up an imported module.
importDeclLookupScope :: ImportDeclOrigin -> ModuleLookupScope
importDeclLookupScope ImplicitEssentialsImport = LookupSystem
importDeclLookupScope ImplicitPreludeImport    = LookupUser
importDeclLookupScope UserWrittenImport        = LookupUser
importDeclLookupScope PluginImport             = LookupUser

-- | Was this import declaration generated or was it written by the user?
isGeneratedImport :: ImportDeclOrigin -> Bool
isGeneratedImport = \case
  UserWrittenImport        -> False
  ImplicitPreludeImport    -> True
  ImplicitEssentialsImport -> True
  PluginImport             -> True

